// Turning Natural Earth's country outlines into the Analytics map's
// (public/js/world-shapes.js), for scripts/world-map.mjs. Pure, so it's easy
// to test.
//
// Every country's rings go into one SVG path, in the map's world units
// (public/js/map-geo.js), rounded to whole units (about 4 km at the
// equator, finer than the 1:110m outlines are) and written as steps from
// the point before, which keeps the file small. Drawn with
// fill-rule="evenodd", holes (a country inside another) stay holes.
// Antarctica is left out: the map stops at 58° south.

import { project } from "../public/js/map-geo.js";

/**
 * @typedef {[number, number]} Position longitude, latitude
 * @typedef {{ type: "Polygon", coordinates: Position[][] } | { type: "MultiPolygon", coordinates: Position[][][] }} Geometry
 * @typedef {{ properties: Record<string, unknown>, geometry: Geometry }} Feature
 */

/**
 * One ring as path steps: a move to its first point, then each next point
 * relative to the one before (points that round to the same spot are
 * dropped), closed. Empty if it rounds to less than a triangle.
 * @param {Position[]} ring
 */
export function ringPath(ring) {
  /** @type {[number, number][]} */
  const points = [];
  for (const [lng, lat] of ring) {
    const { x, y } = project(lat, lng);
    const point = /** @type {[number, number]} */ ([Math.round(x), Math.round(y)]);
    const last = points[points.length - 1];
    if (!last || last[0] !== point[0] || last[1] !== point[1]) points.push(point);
  }
  // The closing point repeats the first.
  const first = points[0], end = points[points.length - 1];
  if (points.length > 1 && first[0] === end[0] && first[1] === end[1]) points.pop();
  if (points.length < 3) return "";
  let d = `M${first[0]} ${first[1]}l`;
  for (let i = 1; i < points.length; i++) {
    const dx = points[i][0] - points[i - 1][0], dy = points[i][1] - points[i - 1][1];
    // A minus sign separates numbers by itself.
    d += (i > 1 && dx >= 0 ? " " : "") + dx + (dy >= 0 ? " " : "") + dy;
  }
  return d + "z";
}

/**
 * Every country but Antarctica as one path.
 * @param {{ features: Feature[] }} collection
 */
export function countriesPath(collection) {
  return collection.features
    .filter((f) => f.properties.ADMIN !== "Antarctica")
    .flatMap((f) => (f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates))
    .flatMap((polygon) => polygon.map(ringPath))
    .filter(Boolean)
    .join("");
}

/**
 * The module the page loads.
 * @param {string} path
 */
export function shapesFile(path) {
  return `// Generated by scripts/world-map.mjs from Natural Earth's 1:110m country
// outlines (public domain, naturalearthdata.com). Don't edit it by hand.

/** Every country's outline as one SVG path, in map-geo.js's world units. */
export const COUNTRIES = ${JSON.stringify(path)};
`;
}
